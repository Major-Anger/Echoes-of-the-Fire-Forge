package fr.anger.echoes.fireforge.module;

/** Les trois côtés de la forge qui acceptent un module (l'avant porte le foyer et le soufflet). */
public enum ModuleSide {
    /** À gauche de la moitié du foyer (vue de face) : la chaudière. */
    LEFT,
    /** Derrière la forge, d'un côté ou de l'autre : le réservoir de lave. */
    BACK,
    /** À droite de la moitié de l'enclume : le module d'amélioration (Forge des âmes, avec le Silt). */
    RIGHT
}
